"""Developer tool: writes requirements-lock.txt, the hashed lock of the whole conversion tree that
scripts/fetch_embedding_model.sh installs with pip's --require-hashes (every package, transitive
ones included, at one version, with the SHA-256 of each file PyPI has for that version).

Resolve on the platform the conversion runs on (macOS arm64, the Python the workflows pin), then
lock from pip's report:
  python3.11 -m venv /tmp/lock-venv
  /tmp/lock-venv/bin/python -m pip install --dry-run --ignore-installed --only-binary=:all: \\
      --report /tmp/lock-report.json -r scripts/embedding_model/requirements.txt
  python3 -I scripts/embedding_model/lock_requirements.py /tmp/lock-report.json \\
      > scripts/embedding_model/requirements-lock.txt
Then run scripts/fetch_embedding_model.sh on a fresh cache: the converted model's checksums must not
change (or are re-pinned on purpose).
"""
import json
import sys
import urllib.request

report = json.load(open(sys.argv[1]))
environment = report["environment"]
print("# Generated by scripts/embedding_model/lock_requirements.py from requirements.txt; don't edit.")
print(f"# Resolved for Python {environment['python_full_version']} on {environment['sys_platform']} "
      f"{environment['platform_machine']}.")
for item in sorted(report["install"], key=lambda item: item["metadata"]["name"].lower()):
    name, version = item["metadata"]["name"], item["metadata"]["version"]
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
        files = json.load(response)["urls"]
    hashes = sorted({file["digests"]["sha256"] for file in files if not file.get("yanked")})
    chosen = item["download_info"]["archive_info"]["hashes"]["sha256"]
    if chosen not in hashes:
        sys.exit(f"lock_requirements: {name} {version}: pip's file isn't among PyPI's files")
    print(f"{name}=={version} \\")
    print(" \\\n".join(f"    --hash=sha256:{digest}" for digest in hashes))

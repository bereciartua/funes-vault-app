#!/usr/bin/env python3
"""Spike F's no-backsliding check: Spike E's fixtures (both sets pooled) with variant A (Spike E's extract-v2 and
decide-v2, the shipped prompt), B and C. Writes results/spike-f/regression.md. Run from this directory."""
import importlib
import json
import os
import sys
from collections import Counter
from pathlib import Path

from compare_sets import numbers

HERE = Path(__file__).resolve().parent
MODELS = ["claude-haiku", "claude-opus", "codex-terra", "codex-sol"]
VARIANTS = {"A": ("extract-v2", "decide-v2"), "B": ("extract-fB", "decide-fB"), "C": ("extract-fC", "decide-fC"),
            "B2": ("extract-fB2", "decide-fB2"), "C2": ("extract-fC2", "decide-fC2"),
            "C3": ("extract-fC3", "decide-fC3")}


def extra(set_name, prov, ext):
    """Pieces, support flags, and wrong claims on the injection inputs."""
    os.environ["SPIKE_SET"] = set_name
    sys.modules.pop("score", None)
    score = importlib.import_module("score")
    recs = score.load(prov, ext)
    c = Counter()
    if not recs:
        return c
    res = score.score_extraction(recs)
    for r in res["rows"]:
        c["pieces"] += 1
        c["flagged"] += bool(r["support"].get("notInInput"))
    inj = {i for i, inp in score.INPUTS.items() if "injection" in inp["tags"]}
    c["inj_wrong"] = sum(1 for w in res["wrong"] if w[0] in inj)
    c["inj_inputs"] = len(inj)
    c["missing"] = sum(1 for i in score.INPUTS if i not in recs)
    return c


def add(a, b):
    if a is None or b is None:
        return a or b
    return (a[0] + b[0], a[1] + b[1])


def f(p):
    return f"{p[0]}/{p[1]} = {100 * p[0] / p[1]:.0f}%" if p and p[1] else "–"


def main():
    lines = ["# Spike F regression on Spike E's fixtures (both sets pooled)", "",
             "A is Spike E's `extract-v2`/`decide-v2` (the shipped prompt). Generated by `regress_f.py`.", ""]
    for prov in MODELS:
        lines += [f"## {prov}", "", "| | " + " | ".join(VARIANTS) + " |", "|---|" + "---|" * len(VARIANTS)]
        cells = {}
        for v, (ext, dec) in VARIANTS.items():
            pooled, ex = {}, Counter()
            for set_name in ("", "astra"):
                n = numbers(set_name, ext, dec).get(prov)
                if n:
                    for k in ("recall", "single_over", "link", "new_dup", "new_all"):
                        pooled[k] = add(pooled.get(k), n[k])
                    pooled["wrong"] = pooled.get("wrong", 0) + n["wrong"]
                ex += extra(set_name, prov, ext)
            cells[v] = (pooled, ex)
        rows = [("Claim recall", lambda p, e: f(p.get("recall"))),
                ("Wrong claims", lambda p, e: str(p.get("wrong", "–"))),
                ("Wrong claims on injection inputs", lambda p, e: f"{e['inj_wrong']} (of {e['inj_inputs']} inputs)"),
                ("Single claims over-split", lambda p, e: f(p.get("single_over"))),
                ("Link accuracy", lambda p, e: f(p.get("link")) if p.get("link") and p["link"][1] else "not run"),
                ("Pieces", lambda p, e: str(e["pieces"])),
                ("Support check flags", lambda p, e: f((e["flagged"], e["pieces"]))),
                ("Inputs not run", lambda p, e: str(e["missing"]))]
        for label, fn in rows:
            lines.append(f"| {label} | " + " | ".join(fn(*cells[v]) for v in VARIANTS) + " |")
        lines.append("")
    out = HERE / "results" / "spike-f" / "regression.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
